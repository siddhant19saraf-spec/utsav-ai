interface SampleCategoryInput {
  readonly id: string;
  readonly name: string;
  readonly plannedRupees: number;
  readonly actualRupees: number;
  readonly protection: 'protected' | 'flexible';
  readonly minimumRupees?: number;
  readonly notes?: string;
}

function sampleBudget(
  eventId: string,
  budgetId: string,
  totalRupees: number,
  reserveRupees: number,
  categoryInputs: readonly SampleCategoryInput[],
  timestamp: string,
): EventBudget {
  const categories: BudgetCategory[] = categoryInputs.map((category) => ({
    id: category.id,
    name: category.name,
    planned: rupees(category.plannedRupees),
    actual: rupees(category.actualRupees),
    flexibility:
      category.protection === 'protected'
        ? { mode: 'protected' }
        : {
            mode: 'flexible',
            minimumPlanned: rupees(category.minimumRupees ?? 0),
          },
    ...(category.notes ? { notes: category.notes } : {}),
  }));

  if (reserveRupees > 0) {
    categories.push({
      id: EMERGENCY_RESERVE_CATEGORY_ID,
      name: 'Emergency reserve',
      planned: rupees(reserveRupees),
      actual: rupees(0),
      flexibility: { mode: 'protected' },
      notes: 'Ring-fenced within the total budget for unexpected costs.',
    });
  }

  return {
    id: budgetId,
    eventId,
    totalAvailable: rupees(totalRupees),
    categories,
    emergencyReserve: {
      enabled: reserveRupees > 0,
      target: rupees(reserveRupees),
    },
    createdAt: timestamp,
    updatedAt: timestamp,
  };
}

